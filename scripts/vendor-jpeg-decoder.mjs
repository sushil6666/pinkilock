/**
 * Writes supabase/functions/photo/mozjpeg_dec.ts: the mozjpeg decoder (WebAssembly, from
 * @jsquash/jpeg, Apache-2.0) as lowercase hex, so the `photo` Edge Function carries it in its own
 * code and never has to find a .wasm file on disk at run time (D098). Hex, not base64: 220 KB of
 * base64 holds strings shaped like cloud keys by chance, which the secret scan rightly flags; hex
 * (0-9, a-f) cannot form them. Run it after changing the @jsquash/jpeg version in package.json;
 * tests/unit/reencode.test.ts fails until you do.
 *
 *   node scripts/vendor-jpeg-decoder.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('node_modules/@jsquash/jpeg/package.json', 'utf8'));
const wasm = readFileSync('node_modules/@jsquash/jpeg/codec/dec/mozjpeg_dec.wasm');
const sha = createHash('sha256').update(wasm).digest('hex');
const hex = wasm.toString('hex').replace(/.{1,128}/g, (line) => `  '${line}',\n`);

writeFileSync('supabase/functions/photo/mozjpeg_dec.ts', `// Generated by scripts/vendor-jpeg-decoder.mjs from @jsquash/jpeg ${pkg.version}
// (codec/dec/mozjpeg_dec.wasm, Apache-2.0, https://github.com/jamsinclair/jSquash). Do not edit.
export const MOZJPEG_DEC_VERSION = '${pkg.version}';
export const MOZJPEG_DEC_SHA256 = '${sha}';
export const MOZJPEG_DEC_HEX = [
${hex}].join('');
`);
console.log(`mozjpeg_dec.ts: @jsquash/jpeg ${pkg.version}, ${wasm.length} bytes, sha256 ${sha}`);
